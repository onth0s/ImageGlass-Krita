# ---------------------------------------------------------------------------
# Helper: send a command to the diag pipe, return response string
# ---------------------------------------------------------------------------
function Send-DiagCmd {
    param([string] $Cmd)
    $pipeName = 'imageglass_diag'
    $maxAttempts = 5
    for ($attempt = 1; $attempt -le $maxAttempts; $attempt++) {
        try {
            $pipe = [System.IO.Pipes.NamedPipeClientStream]::new('.', $pipeName,
                [System.IO.Pipes.PipeDirection]::InOut,
                [System.IO.Pipes.PipeOptions]::None)
            $pipe.Connect(3000)

            $bytes = [System.Text.Encoding]::UTF8.GetBytes("$Cmd`n")
            $pipe.Write($bytes, 0, $bytes.Length)
            $pipe.Flush()

            $buffer = [byte[]]::new(8192)
            $read = $pipe.Read($buffer, 0, $buffer.Length)
            $pipe.Dispose()

            if ($read -gt 0) {
                return [System.Text.Encoding]::UTF8.GetString($buffer, 0, $read).Trim()
            }
        }
        catch {
            if ($attempt -eq $maxAttempts) { throw }
            Start-Sleep -Milliseconds 200
        }
    }
}

# Helper: QUERY returns parsed JSON object
function Query-DiagPipe {
    $json = Send-DiagCmd 'QUERY'
    return ($json | ConvertFrom-Json)
}

# Helper: wait until expected photo is fully loaded in viewer
function Wait-PhotoLoaded {
    param([string] $ExpectedFileName, [int] $TimeoutMs = 4000)
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    while ($sw.ElapsedMilliseconds -lt $TimeoutMs) {
        $state = Query-DiagPipe
        if ($state.FilePath -and (Split-Path $state.FilePath -Leaf) -eq $ExpectedFileName) {
            # Extra small pause for layout stabilization
            Start-Sleep -Milliseconds 100
            return (Query-DiagPipe)
        }
        Start-Sleep -Milliseconds 150
    }
    return (Query-DiagPipe)
}

# Helper: set zoom ratio (multiple of ScaleToFit)
function Set-Zoom {
    param([double] $Ratio)
    return (Send-DiagCmd "SET_ZOOM $Ratio")
}

# Helper: set pan position (0..1 fractions)
function Set-Pan {
    param([double] $NormX, [double] $NormY)
    return (Send-DiagCmd "SET_PAN $NormX $NormY")
}

# Helper: navigate image list by delta
function Navigate {
    param([int] $Delta = 1, [int] $WaitMs = 1000)
    Send-DiagCmd "NAVIGATE $Delta" | Out-Null
    Start-Sleep -Milliseconds $WaitMs
}

# ---------------------------------------------------------------------------
# Helper: print PASS / FAIL
# ---------------------------------------------------------------------------
$script:Results = [System.Collections.Generic.List[PSCustomObject]]::new()

function Assert-Test {
    param(
        [string] $TestName,
        [bool]   $Condition,
        [string] $Details = ''
    )
    if ($Condition) {
        Write-Host "  [PASS] $TestName" -ForegroundColor Green
        $script:Results.Add([PSCustomObject]@{ Test = $TestName; Result = 'PASS'; Details = '' })
    }
    else {
        Write-Host "  [FAIL] $TestName" -ForegroundColor Red
        if ($Details) { Write-Host "         $Details" -ForegroundColor Yellow }
        $script:Results.Add([PSCustomObject]@{ Test = $TestName; Result = 'FAIL'; Details = $Details })
    }
}

