    $centerA4 = Get-ViewportCenterFrac $stateA4
    Write-Host "  [DBG] A initial: ZoomRatio=$($stateA4.SharedZoomRatio) CenterFrac=($([Math]::Round($centerA4.FracX,3)), $([Math]::Round($centerA4.FracY,3))) R=$($centerA4.R) G=$($centerA4.G)"

    Navigate -Delta 1   # B
    Navigate -Delta 1   # C (portrait - pan X margin-clamped to prevent empty gap)
    $stateC4 = Query-DiagPipe
    $centerC4 = Get-ViewportCenterFrac $stateC4
    Write-Host "  [DBG] C portrait: ZoomRatio=$($stateC4.SharedZoomRatio) CenterFrac=($([Math]::Round($centerC4.FracX,3)), $([Math]::Round($centerC4.FracY,3))) R=$($centerC4.R) G=$($centerC4.G)"

    # Navigate back C → B → A
    Navigate -Delta -1  # B
    Navigate -Delta -1  # A
    $stateA4_return = Query-DiagPipe
    $centerA4_return = Get-ViewportCenterFrac $stateA4_return
    Write-Host "  [DBG] A returned: ZoomRatio=$($stateA4_return.SharedZoomRatio) CenterFrac=($([Math]::Round($centerA4_return.FracX,3)), $([Math]::Round($centerA4_return.FracY,3))) R=$($centerA4_return.R) G=$($centerA4_return.G)"

    Assert-Test 'T4-ZoomRatioPreserved' `
        ([Math]::Abs($stateA4_return.SharedZoomRatio - $stateA4.SharedZoomRatio) -lt 0.01) `
        "A.ZoomRatio=$($stateA4.SharedZoomRatio)  A_return.ZoomRatio=$($stateA4_return.SharedZoomRatio)"

    Assert-Test 'T4-RenderedColorMatch-R' `
        ([Math]::Abs($centerA4_return.R - $centerA4.R) -le 2) `
        "A.R=$($centerA4.R)  A_return.R=$($centerA4_return.R)"

    Assert-Test 'T4-RenderedColorMatch-G' `
        ([Math]::Abs($centerA4_return.G - $centerA4.G) -le 2) `
        "A.G=$($centerA4.G)  A_return.G=$($centerA4_return.G)"

    # -----------------------------------------------------------------------
    # T5 – Round-trip A→B→C→D→A zoom ratio preserved
    # -----------------------------------------------------------------------
    Write-Host "`n--- T5: Round-trip A→B→C→D→A ---"

    # navigate back to A (currently on C, two lefts)
    Navigate -Delta -1; Navigate -Delta -1

    Set-Zoom -Ratio 2.0 | Out-Null
    $ratioBeforeTrip = (Query-DiagPipe).SharedZoomRatio

    Navigate -Delta 1   # B
    Navigate -Delta 1   # C
    Navigate -Delta 1   # D
    Navigate -Delta 1   # A (wraps)

    $stateRT = Query-DiagPipe
    Write-Host "  [DBG] Round-trip: before=$ratioBeforeTrip  after=$($stateRT.SharedZoomRatio)"

    Assert-Test 'T5-RoundTripZoomRatio' `
        ([Math]::Abs($stateRT.SharedZoomRatio - $ratioBeforeTrip) -lt 0.01) `
        "expected=$ratioBeforeTrip  actual=$($stateRT.SharedZoomRatio)"

    # -----------------------------------------------------------------------
    # T6 – Arbitrary cursor zoom-to-point (200, 150) homology A → B
    # -----------------------------------------------------------------------
    Write-Host "`n--- T6: Zoom to cursor point (200, 150) preserved A → B ---"

    Navigate -Delta -1; Navigate -Delta -1; Navigate -Delta -1 # back to A
    $stateA6_init = Wait-PhotoLoaded 'A_large_landscape.png'
    Zoom-ToPoint -Ratio 2.5 -ScreenX 200 -ScreenY 150 | Out-Null
    Start-Sleep -Milliseconds 400

    $stateA6 = Query-DiagPipe
    $ptA6 = Get-PointPixelColor $stateA6 200 150
    Write-Host "  [DBG] A at (200,150): Frac=($([Math]::Round($ptA6.FracX,3)), $([Math]::Round($ptA6.FracY,3))) R=$($ptA6.R) G=$($ptA6.G)"

    Navigate -Delta 1  # B
    $stateB6 = Wait-PhotoLoaded 'B_small_landscape.png'
    $ptB6 = Get-PointPixelColor $stateB6 200 150
    Write-Host "  [DBG] B at (200,150): Frac=($([Math]::Round($ptB6.FracX,3)), $([Math]::Round($ptB6.FracY,3))) R=$($ptB6.R) G=$($ptB6.G)"

    Assert-Test 'T6-CursorColorMatch-R' `
        ([Math]::Abs($ptB6.R - $ptA6.R) -le 2) `
        "A.R=$($ptA6.R)  B.R=$($ptB6.R)"

    Assert-Test 'T6-CursorColorMatch-G' `
        ([Math]::Abs($ptB6.G - $ptA6.G) -le 2) `
        "A.G=$($ptA6.G)  B.G=$($ptB6.G)"
}
finally {
